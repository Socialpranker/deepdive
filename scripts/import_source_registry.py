        "## Обновление",
        "",
        "```bash",
        "python scripts/import_source_registry.py --source <путь>/sources.csv --min-value 5",
        "```",
        "",
        "Порог `--min-value 3` даёт примерно втрое больше записей — расширять осознанно, "
        "каталог платит за это контекстом.",
