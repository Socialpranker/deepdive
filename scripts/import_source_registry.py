def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--source", type=Path, required=True, help="scouting CSV (private, not in repo)"
    )
    ap.add_argument(
        "--out", type=Path, default=Path("references/registry"), help="output directory"
    )
    ap.add_argument(
        "--min-value", type=int, default=5, help="keep rows with value_score >= this"
    )
    ap.add_argument(
        "--verified", default="2026-08-05", help="scouting date claimed by the input"
    )
    ap.add_argument(
        "--dry-run", action="store_true", help="report counts, write nothing"
    )
    args = ap.parse_args()

    if not args.source.is_file():
        print(f"error: {args.source} not found", file=sys.stderr)
        return 2

    routed, dropped, problems = load(args.source, args.min_value)
    if not routed:
        print(
            "error: nothing passed the filters — check --min-value and the input",
            file=sys.stderr,
        )
        return 1

    print(f"source: {args.source}")
    for label, n in dropped.most_common():
        print(f"  dropped {n:5d}  ({label})")
    print(f"  kept    {sum(len(v) for v in routed.values()):5d}")
    for filename in sorted(routed, key=lambda k: -len(routed[k])):
        print(f"    {filename:28s} {len(routed[filename]):5d}")
    for p in problems:
        print(f"  WARN {p}")

    if args.dry_run:
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for filename, rows in routed.items():
        (args.out / filename).write_text(
            render(filename, rows, args.verified, args.min_value), encoding="utf-8"
        )
    (args.out / "INDEX.md").write_text(
        render_index(routed, args.verified, args.min_value), encoding="utf-8"
    )
    print(f"wrote {len(routed) + 1} files to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
